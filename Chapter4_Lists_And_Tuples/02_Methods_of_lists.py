list = [2,3,4,6,9,0,5,]
list.sort()                #Update the list to [0,2,3,4,5,6,9]
print(list)

list.reverse()             #Update the list to [9,6,5,4,3,2,0]
print(list) 

list.insert(3,7)           #Insert 7 on the 3rd index
print(list)

list.pop(2)                # Delete the element present at index 2
print(list)

list.remove(6)             # Delete the element 6 from the list
print(list)