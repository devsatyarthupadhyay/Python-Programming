s = {1,3,5,7,9,2,4,6,8}   

s.add(31)       # this method is used to add element in set 
print(s)          

len(s)          # it is used to find length of the set  , the number of elements in the set
print(len(s))

s.remove(8)      #This method is used to remove desired element from the set
print(s)

s.pop()         # This method is used to remove any arbitrary element from the set
print(s)

s.clear()       # This method will clear the set
print(s)